"""
Загрузка урезанной базы материалов лид-бота (data/materials_lead.json).

ПОЧЕМУ ИМЕННО ЭТИ 9 МАТЕРИАЛОВ (3 уровня × 3 материала)
---------------------------------------------------------
Воронка по архитектуре — это 3 порции с разной ролью, поэтому на каждый
уровень (A1 / A2 / B1 — остальных в исходной базе просто нет) взято ровно
по одному материалу на каждую роль:

1. "Быстрый вин" (подкаст, 1 минута + задания с ключами).
   Короткий, самодостаточный, с самопроверкой — идеально для первого
   касания: результат виден за 5 минут, не требует усилий на старте.
   Для A2/B1 внутри уровня выбраны подкасты про повседневную рутину/работу
   ("My morning routine", "My First Day at Work") — тема максимально
   нейтральная и откликается почти любому сегменту (self/work/travel),
   поэтому именно на неё завязана персонализация приветственного текста.

2. "Углубление" (адаптированная книга).
   Здесь принципиально взяты УЗНАВАЕМЫЕ произведения (Снежная королева,
   Алиса в Стране чудес, Портрет Дориана Грея) — это даёт материалу
   воспринимаемую ценность ("о, я знаю эту историю") сильнее, чем
   технически "более лёгкий" текст, который человек видит впервые.

3. "Крючок на курс" (первая серия сериала).
   Всегда именно Episode 1 — не спойлерит, сериал ещё не начат, поэтому
   логично предлагать "досмотреть с нами" на групповом курсе по сериалам.
   Комедийные / фэнтези-сериалы выбраны из соображений максимального охвата
   аудитории (self-dev, 25–35 лет) — они легче "залипают" на первой серии,
   чем нишевый драматический контент.

Материалов на уровень намеренно всего 3, а не 5-10: задача лид-магнита —
довести человека до заявки за 3-4 касания, а не заменить собой курс.
Весь остальной объём (десятки эпизодов, подкастов, книг) остаётся в
закрытом студенческом боте как стимул "перейти дальше".
"""

import json

from config import MATERIALS_PATH

_LEVELS = ("A1", "A2", "B1")


def load_lead_materials() -> dict:
    with open(MATERIALS_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def available_levels() -> tuple:
    return _LEVELS


def get_podcast(level: str) -> dict:
    return load_lead_materials()[level]["podcast"]


def get_book(level: str) -> dict:
    return load_lead_materials()[level]["book"]


def get_series(level: str) -> dict:
    """Возвращает {'show': str, 'episode': {...}}."""
    return load_lead_materials()[level]["series"]
